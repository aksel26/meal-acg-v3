UPDATE supervisor.workers SET status = 'contracted'
WHERE id IN (SELECT DISTINCT worker_id FROM supervisor.assignments)
  AND status = 'registered';

-- 2) 그 중 출석 기록이 있는 worker를 working으로 (contracted → working)
UPDATE supervisor.workers SET status = 'working'
WHERE id IN (
  SELECT DISTINCT worker_id FROM supervisor.assignments
  WHERE attendance_status IN ('checked_in', 'confirmed')
);

